#!/usr/bin/env python3
"""Rebuild all stored prompts with the current builder (build_prompt_v42 + v48 sync: brand/name line, R-NOHANDLES, commenter images off).
Same specs/fixes/holds as regen_v42. Output prompts_v43/, out/diff-v43.json, out/DIFF-v43.md. prompts_v42 untouched. No renders, no paid calls."""
import os,sys,json
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
import regen_v42 as R42, regen_v41 as R41, regen_pending_v4 as RG
H=R41.H; OUT=f"{H}/prompts_v43"
R42.OUT=OUT; R41.OUT=OUT; R41.LOG.clear()
if __name__=="__main__":
    assert not os.path.exists(OUT), "prompts_v43 exists; refusing to overwrite"
    for fn in (RG.odyssey,RG.round9,RG.commercials,RG.lipsync): fn([])
    v42={x["id"]:x for x in json.load(open(f"{H}/out/diff-v42.json"))}
    LOG=R41.LOG
    for x in LOG: x["v43"]=x.pop("v41"); x["v42"]=v42.get(x["id"],{}).get("v42"); x["v42_status"]=v42.get(x["id"],{}).get("status")
    json.dump(LOG,open(f"{H}/out/diff-v43.json","w"),indent=1)
    ok=[x for x in LOG if x["status"]=="OK"]
    with open(f"{H}/out/DIFF-v43.md","w") as f:
        f.write(f"# v4.2 -> v4.3 stored-prompt rebuild (v48 sync bracket)\nGenerated by tools/regen_v43.py. No renders.\n\n{len(ok)} OK / {len(LOG)}.\n\n| id | v4.2 | v4.3 | why |\n|---|---|---|---|\n")
        for x in LOG: f.write(f"| {x['id']} | {x['v42_status']} | {x['status']} | {'; '.join(map(str,x['fails']))[:300]} |\n")
    print(len(ok),"OK /",len(LOG))
    for x in LOG:
        if x["status"]!="OK": print(x["status"],x["id"],x["fails"])
