"""Build live/ref-index.yaml: real, existing reference stills for live commenter clips. Local only; reads files, no API calls."""
import yaml, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
BIBLE = ROOT / "continuity/ch04-military-boutique/bible-v2.yaml"
RUN2 = ROOT / "data/pilots/ch04-forward-supply-run2-20261027"
R = RUN2 / "run2/renders-480p-20261027_1547"
F = R / "frames"
ML = Path("/workspace/shared/media-library/ch04-military-boutique/cnb-series")
b = yaml.safe_load(open(BIBLE))
ALIASES = {"osmund": ["osmund", "oz"], "mira_smirin": ["mira", "lt. mira", "s'mirin"], "tim": ["tim"],
           "bill_dbears": ["bill", "commander", "d'bears", "dbears"]}
def ex(p): return str(p) if p and Path(p).is_file() else None
idx = {"meta": {"built_from": [str(BIBLE), str(RUN2 / "clip-prompts.json"), str(R / "log.jsonl"), str(F), str(ML)],
                "rule": "Every path below was checked to exist when built. Cast = Bible-locked stills (exactly what Run 2 sent). "
                        "Locations/products = frames from Run 2 renders (not Bible-locked; trundle has not reviewed them as refs).",
                "rebuild": "python live/build_ref_index.py"},
       "cast": {}, "locations": {}, "products": {}, "missing": [],
       "default_crew": ["osmund", "mira_smirin", "bill_dbears", "tim"], "default_location": "mess_hall",
       "continuity_anchor": {"source_mp4": str(R / "S7D_480p_grok-imagine-video-1.5_parody.mp4"), "frame": "last_frame",
                             "shot": "S7D", "note": "Run 2 final shot. CNB extracts the last frame at render time."}}
for k, c in b["cast"].items():
    if not isinstance(c, dict) or "still" not in c: continue
    paths = [p for p in [c["still"]] + list(c.get("turnaround_paths") or []) if p]
    ok = [p for p in dict.fromkeys(paths) if ex(p)]
    idx["missing"] += [f"cast {k}: {p}" for p in paths if not ex(p)]
    idx["cast"][k] = {"aliases": ALIASES.get(k, [k]), "primary": ok[0] if ok else None, "stills": ok, "source": "bible-v2 cast (locked)"}
LOC = {"mess_hall": ("S1A", ["mess hall", "mess", "table", "porthole", "coffee"]), "supply_bay": ("S2G", ["supply bay", "bay", "shelf", "shelving", "supply"]),
       "hatch": ("S3E", ["hatch", "gantry", "mast", "outside", "relay"]), "bunk_room": ("S4C", ["bunk", "keepsake", "sleep", "bed"]),
       "command_hut": ("S5B", ["command hut", "hut", "desk", "envelope", "office", "map board"])}
for k, (shot, al) in LOC.items():
    p = ex(F / f"{shot}_0.jpg")
    if not p: idx["missing"].append(f"location {k}: {F}/{shot}_0.jpg")
    idx["locations"][k] = {"aliases": al, "still": p, "source": f"run2 frame {shot}_0 (first frame)"}
PROD = {"quietline-helmet": "S3C", "strataclip-ration-tin": "S3B", "thermal-ration-pack": "S2A", "valuables-motion-guard": "S6B",
        "sky-diffuser": "S2E", "lightning-lamp": "S7D"}
CLIP = {"modular-field-pack": "modular-field-pack", "armored-showroom-cruiser": "armored-showroom-cruiser", "exo-gauntlet": "exo-gauntlet-vitrine",
        "scout-drone": "scout-drone-jewelry", "field-binoculars": "field-binoculars-velvet", "graphite-cloak": "graphite-cloak-torso",
        "quietline-helmet": "tactical-helmet-pedestal"}
NOTES = {"sky-diffuser": "S2E flagged: diffuser reads like a foggy window", "lightning-lamp": "frame also has full cast"}
for p in b["product_registry"]["products"]:
    i, name = p["id"], p["name"]
    al = [name.lower(), i.replace("-", " ")] + [w for w in name.lower().replace("(", " ").split() if len(w) > 5 and w not in ("helmet", "cavity", "ration", "field")][:1]
    still = ex(F / f"{PROD[i]}_1.jpg") if i in PROD else None
    clips = sorted(str(x) for x in ML.glob(f"*{CLIP[i]}*.mp4")) if i in CLIP else []
    e = {"aliases": list(dict.fromkeys(al)), "still": still, "source": f"run2 frame {PROD[i]}_1" if still else None, "source_clips": clips}
    if i in NOTES: e["note"] = NOTES[i]
    if not still: idx["missing"].append(f"product {i}: no still" + (" (CNB clip exists; extract a frame to add one)" if clips else " and no clip"))
    idx["products"][i] = e
out = Path(__file__).parent / "ref-index.yaml"
out.write_text("# Generated by build_ref_index.py - do not hand-edit paths\n" + yaml.safe_dump(idx, sort_keys=False, allow_unicode=True, width=200))
print(json.dumps({"cast": {k: len(v["stills"]) for k, v in idx["cast"].items()}, "locations": sum(1 for v in idx["locations"].values() if v["still"]),
                  "products_with_still": sum(1 for v in idx["products"].values() if v["still"]), "products": len(idx["products"]), "missing": idx["missing"]}, indent=1))
