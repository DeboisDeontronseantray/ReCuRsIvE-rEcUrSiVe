"""Single registry and cheapest compatible fix selection; no repair is executed."""
from .contracts import now

FIXES = [
    {'id': 'zipper', 'problem_solved': ['seam pop'], 'conditions': ['overlap_frames'], 'cost_class': 'free ffmpeg', 'conflicts': ['identity_mismatch'], 'version': 1},
    {'id': 'crt-bridge', 'problem_solved': ['seam pop', 'style drift'], 'conditions': ['bridge_allowed'], 'cost_class': 'free ffmpeg', 'conflicts': ['continuous_take'], 'version': 1},
    {'id': 'impact', 'problem_solved': ['weak contact'], 'conditions': ['contact_frame'], 'cost_class': 'free ffmpeg', 'conflicts': [], 'version': 1},
    {'id': 'refresh-still', 'problem_solved': ['morph', 'style drift'], 'conditions': ['reference_review'], 'cost_class': 'still', 'conflicts': [], 'version': 1},
    {'id': 'regen', 'problem_solved': ['seam pop', 'standing around', 'style drift', 'morph'], 'conditions': ['cheaper_fixes_exhausted'], 'cost_class': 'full regen', 'conflicts': [], 'version': 1},
]
RANK = {'free ffmpeg': 0, 'still': 1, 'full regen': 2}


def record(state, failure_type, clip_id, evidence, conditions=()):
    choices = [f for f in state['fix_library'] if failure_type in f['problem_solved']
               and set(f['conditions']) <= set(conditions) and not set(f['conflicts']) & set(conditions)]
    # These shots must be generated by prompts, never recommended as a still/edit seam repair.
    if set(conditions) & {'portal', 'pivot', 'portal_move', 'pivot_move'}:
        choices = []
    chosen = min(choices, key=lambda f: (RANK[f['cost_class']], f['id'])) if choices else None
    row = {'id': len(state['problems']) + 1, 'version': 1, 'failure_type': failure_type,
           'clip_id': clip_id, 'evidence': evidence, 'timestamp': now(),
           'fix_id': chosen['id'] if chosen else None, 'status': 'open', 'resolution': None}
    state['problems'].append(row)
    if chosen:
        state['fix_queue'].append({'problem_id': row['id'], 'fix_id': chosen['id'], 'status': 'proposed'})
    return row
